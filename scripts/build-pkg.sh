#!/usr/bin/env bash
# Build a native Arch Linux package (x86_64) from the tested AppImage.
#
# The payload is unpacked rather than wrapped: /usr/bin gets the GUI, the sync
# engine and the dispatcher, the official CLI lives in /usr/lib/proton-drive,
# and a vendor systemd user unit makes syncing a package service. No makepkg,
# fakeroot or pacman needed to build - only bsdtar (libarchive) and zstd.
#
# Usage: scripts/build-pkg.sh [x86_64]
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST="$ROOT/dist"
LOCK="$ROOT/upstream.lock"
PKG="proton-drive"
PKGREL="1"
ARCH="x86_64"

die() { printf 'build-pkg: %s\n' "$*" >&2; exit 1; }
lock_get() { awk -F= -v key="$1" '$1 == key { sub(/^[^=]*=/, ""); print; exit }' "$LOCK"; }
log() { printf 'build-pkg: %s\n' "$*"; }

VERSION="$(lock_get VERSION)"
GUI_VERSION="$(sed -n 's/^pub const GUI_VERSION: &str = "\(.*\)";$/\1/p' "$ROOT/gui/src/main.rs" | head -1)"
[ -n "$VERSION" ] && [ -n "$GUI_VERSION" ] || die "missing VERSION or GUI_VERSION"

case "${1:-$ARCH}" in
    x86_64) ;;
    *) die "only x86_64 is packaged (got: $1)" ;;
esac

app="$DIST/ProtonDrive-CLI-${VERSION}-GUI-${GUI_VERSION}-${ARCH}.AppImage"
[ -f "$app" ] || die "missing $app - run ./build.sh ${ARCH} first"
for tool in bsdtar tar zstd gzip install; do
    command -v "$tool" >/dev/null 2>&1 \
        || die "$tool not found (Arch: pacman -S libarchive zstd; Debian: libarchive-tools zstd)"
done

work="$(mktemp -d /tmp/proton-pkg.XXXXXX)"
cleanup() { rm -rf "$work"; }
trap cleanup EXIT

log "unpacking $(basename "$app")"
( cd "$work" && APPIMAGE_EXTRACT_AND_RUN=1 "$app" --appimage-extract >/dev/null )
src="$work/squashfs-root"
root="$work/root"

for f in usr/bin/proton-drive usr/bin/proton-drive-gui usr/bin/proton-engine \
         usr/share/applications/io.github.zhafribs.protondrivecli.desktop \
         usr/share/metainfo/io.github.zhafribs.protondrivecli.appdata.xml \
         usr/lib/proton-sync/protondrive-icon.svg; do
    [ -f "$src/$f" ] || die "AppImage payload is missing $f"
done

# A native tree: the dispatcher is the command, the GUI and engine sit beside
# it, and the unmodified official CLI is not shadowed on PATH.
install -Dm0755 "$ROOT/packaging/arch/proton-drive" "$root/usr/bin/proton-drive"
install -Dm0755 "$src/usr/bin/proton-drive-gui" "$root/usr/bin/proton-drive-gui"
install -Dm0755 "$src/usr/bin/proton-engine" "$root/usr/bin/proton-engine"
install -Dm0755 "$src/usr/bin/proton-drive" "$root/usr/lib/proton-drive/proton-drive"
# The in-app updater reads this marker: it installs a new package with
# pacman/polkit instead of trying to swap an AppImage that is not there.
printf 'arch\n' > "$root/usr/lib/proton-drive/package"
chmod 0644 "$root/usr/lib/proton-drive/package"

install -Dm0644 "$src/usr/share/applications/io.github.zhafribs.protondrivecli.desktop" \
    "$root/usr/share/applications/io.github.zhafribs.protondrivecli.desktop"
install -Dm0644 "$src/usr/share/metainfo/io.github.zhafribs.protondrivecli.appdata.xml" \
    "$root/usr/share/metainfo/io.github.zhafribs.protondrivecli.appdata.xml"
for size in 256 512; do
    install -Dm0644 "$src/usr/share/icons/hicolor/${size}x${size}/apps/proton-drive.png" \
        "$root/usr/share/icons/hicolor/${size}x${size}/apps/proton-drive.png"
done
# One SVG serves the desktop entry (proton-drive) and the GUI's own menu and
# notification icon lookup (proton-drive-gui), so neither path can go blank.
install -Dm0644 "$src/usr/lib/proton-sync/protondrive-icon.svg" \
    "$root/usr/share/icons/hicolor/scalable/apps/proton-drive.svg"
install -Dm0644 "$src/usr/lib/proton-sync/protondrive-icon.svg" \
    "$root/usr/share/icons/hicolor/scalable/apps/proton-drive-gui.svg"

install -Dm0644 "$ROOT/LICENSE" "$root/usr/share/licenses/$PKG/LICENSE"
install -Dm0644 "$src/usr/share/licenses/proton-drive-gui-THIRD-PARTY.txt" \
    "$root/usr/share/licenses/$PKG/THIRD-PARTY.txt"

# The package owns the sync unit in systemd's vendor directory. The GUI reads
# it from there (service::unit_exists), so Start/Pause/Start-at-login work in
# a native install instead of looking like no service exists.
sed "s|@GUI_VERSION@|${GUI_VERSION}|g" \
    "$ROOT/packaging/arch/proton-sync.service" \
    > "$work/proton-sync.service"
if grep -q '@GUI_VERSION@' "$work/proton-sync.service"; then
    die "systemd unit still has an unsubstituted version"
fi
install -Dm0644 "$work/proton-sync.service" \
    "$root/usr/lib/systemd/user/proton-sync.service"

# Installed size in bytes, exactly as makepkg records it (sum of file sizes;
# .PKGINFO itself is written afterwards and is not counted).
size="$(find "$root" -type f -printf '%s\n' | awk '{s += $1} END {print s + 0}')"
epoch="${SOURCE_DATE_EPOCH:-$(git -C "$ROOT" log -1 --format=%ct 2>/dev/null || date +%s)}"

cat > "$root/.PKGINFO" <<PKGINFO
# Generated by proton-drive scripts/build-pkg.sh
pkgname = $PKG
pkgbase = $PKG
xdata = pkgtype=pkg
pkgver = ${VERSION}+gui${GUI_VERSION}-${PKGREL}
pkgdesc = Unofficial Proton Drive desktop app with the official CLI inside
url = https://github.com/zhafribs/Proton-Drive-Linux-Cli
builddate = $epoch
packager = Zhafri Syazwi <zhafribs@users.noreply.github.com>
size = $size
arch = $ARCH
license = MIT
depend = glibc
depend = fontconfig
depend = libglvnd
depend = libx11
depend = libxcb
depend = libxcursor
depend = libxi
depend = libxkbcommon
depend = libxkbcommon-x11
depend = libxrandr
depend = libxrender
depend = wayland
optdepend = polkit: in-app update asks for your password instead of printing a command
PKGINFO

# Reproducible: every member gets the same mtime, and the archive is sorted.
find "$root" -exec touch -h -d "@$epoch" {} +
( cd "$root" && bsdtar --uid 0 --gid 0 --uname root --gname root -cf "$work/mtree" \
    --format=mtree \
    --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' . )
# gzip -n: no timestamp or file name in the header, so two builds match.
gzip -n -9 -c "$work/mtree" > "$root/.MTREE"

out="$DIST/${PKG}-${VERSION}+gui${GUI_VERSION}-${PKGREL}-${ARCH}.pkg.tar.zst"
mkdir -p "$DIST"
rm -f "$out"
tar --sort=name --mtime="@${epoch}" --owner=0 --group=0 --numeric-owner \
    -C "$root" -cf - .PKGINFO .MTREE usr | zstd -q -c -T0 -9 > "$out"

log "built $out ($(du -h "$out" | cut -f1))"
